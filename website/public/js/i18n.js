const LANG_NAMES = {
  en: { en: 'English', de: 'German', fr: 'French' },
  de: { en: 'Englisch', de: 'Deutsch', fr: 'Französisch' },
};

function detectLang() {
  try {
    const saved = localStorage.getItem('lang');
    if (saved === 'en' || saved === 'de') return saved;
  } catch {}
  return (navigator.language || '').toLowerCase().startsWith('de') ? 'de' : 'en';
}

let currentLang = detectLang();

function t(key, ...args) {
  const v = (JS_STRINGS[currentLang] || JS_STRINGS.en)[key] ?? JS_STRINGS.en[key];
  return typeof v === 'function' ? v(...args) : v;
}

function langName(code) {
  return (LANG_NAMES[currentLang] || LANG_NAMES.en)[code] || code;
}

function applyLang(lang) {
  currentLang = lang;
  const dict = I18N[lang] || {};
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    if (el.dataset.en === undefined) el.dataset.en = el.innerHTML;
    el.innerHTML = lang === 'en' ? el.dataset.en : (dict[el.dataset.i18n] ?? el.dataset.en);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    if (el.dataset.enPh === undefined) el.dataset.enPh = el.placeholder;
    el.placeholder = lang === 'en' ? el.dataset.enPh : (dict[el.dataset.i18nPlaceholder] ?? el.dataset.enPh);
  });
  document.documentElement.lang = lang;
  document.querySelectorAll('.lang-switch button').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
  try { localStorage.setItem('lang', lang); } catch {}
  document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.lang-switch button').forEach((b) => b.addEventListener('click', () => applyLang(b.dataset.lang)));
  applyLang(currentLang);
});
